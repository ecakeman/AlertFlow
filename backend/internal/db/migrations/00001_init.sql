-- AlertFlow runtime schema for a new PostgreSQL database.
-- This is the shape after upstream SQLite migrations 00001–00006, including
-- check attempts, warning status, incident severity, nullable warning logs
-- and the one-ongoing-incident partial unique index. Unix timestamps stay
-- BIGINT so existing API time fields do not change.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('admin', 'readonly')),
    created_at    BIGINT NOT NULL
);

CREATE TABLE sessions (
    token      TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX idx_sessions_expires ON sessions (expires_at);

CREATE TABLE checks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id  TEXT NOT NULL,
    ts          BIGINT NOT NULL,
    status      TEXT NOT NULL CHECK (status IN ('online', 'offline', 'warning', 'unknown')),
    latency_ms  INTEGER,
    status_code INTEGER,
    error       TEXT,
    attempts    INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX idx_checks_service_ts ON checks (service_id, ts);
CREATE INDEX idx_checks_service_id ON checks (service_id, id);
CREATE INDEX idx_checks_status_ts ON checks (status, ts);

CREATE TABLE service_tls (
    service_id  TEXT PRIMARY KEY,
    checked_at  BIGINT NOT NULL,
    valid_from  BIGINT,
    valid_until BIGINT,
    issuer      TEXT,
    subject     TEXT,
    error       TEXT
);

CREATE TABLE incidents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id  TEXT NOT NULL,
    status      TEXT NOT NULL CHECK (status IN ('ongoing', 'resolved')),
    source      TEXT NOT NULL CHECK (source IN ('auto', 'manual')),
    severity    TEXT NOT NULL DEFAULT 'outage' CHECK (severity IN ('outage', 'warning')),
    title       TEXT,
    started_at  BIGINT NOT NULL,
    resolved_at BIGINT,
    created_by  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at  BIGINT NOT NULL,
    updated_at  BIGINT NOT NULL
);
CREATE INDEX idx_incidents_service ON incidents (service_id, started_at);
CREATE INDEX idx_incidents_status ON incidents (status);
CREATE UNIQUE INDEX idx_incidents_one_ongoing ON incidents (service_id) WHERE status = 'ongoing';

CREATE TABLE incident_comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    user_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    body        TEXT NOT NULL,
    created_at  BIGINT NOT NULL
);
CREATE INDEX idx_incident_comments_incident ON incident_comments (incident_id, created_at);

CREATE TABLE integrations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            TEXT NOT NULL CHECK (type IN ('telegram', 'slack', 'email', 'webhook')),
    name            TEXT NOT NULL,
    enabled         BOOLEAN NOT NULL DEFAULT TRUE,
    notify_warnings BOOLEAN NOT NULL DEFAULT FALSE,
    config          JSONB NOT NULL,
    created_at      BIGINT NOT NULL,
    updated_at      BIGINT NOT NULL
);

CREATE TABLE notification_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    integration_id BIGINT NOT NULL REFERENCES integrations (id) ON DELETE CASCADE,
    incident_id    BIGINT REFERENCES incidents (id) ON DELETE CASCADE,
    event          TEXT NOT NULL CHECK (event IN ('incident_start', 'incident_resolve', 'warning')),
    status         TEXT NOT NULL CHECK (status IN ('sent', 'failed')),
    error          TEXT,
    sent_at        BIGINT NOT NULL
);
CREATE INDEX idx_notification_log_integration ON notification_log (integration_id, sent_at);
CREATE INDEX idx_notification_log_incident ON notification_log (incident_id);

-- +goose Down
DROP TABLE IF EXISTS notification_log;
DROP TABLE IF EXISTS integrations;
DROP TABLE IF EXISTS incident_comments;
DROP TABLE IF EXISTS incidents;
DROP TABLE IF EXISTS service_tls;
DROP TABLE IF EXISTS checks;
DROP TABLE IF EXISTS sessions;
DROP TABLE IF EXISTS users;
