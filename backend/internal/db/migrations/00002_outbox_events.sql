-- +goose Up
-- Outbox rows are created in the same transaction as the check they describe.
-- published_at stays NULL until a later publisher marks a real broker ack.
CREATE TABLE outbox_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        TEXT NOT NULL UNIQUE,
    event_type      TEXT NOT NULL,
    schema_version  INTEGER NOT NULL,
    message_key     TEXT NOT NULL,
    payload         JSONB NOT NULL,
    created_at      BIGINT NOT NULL,
    published_at    BIGINT,
    attempt_count   INTEGER NOT NULL DEFAULT 0,
    next_attempt_at BIGINT NOT NULL,
    last_error      TEXT,
    lease_owner     TEXT,
    lease_until     BIGINT
);
CREATE INDEX idx_outbox_pending ON outbox_events (next_attempt_at, id)
    WHERE published_at IS NULL;

-- +goose Down
DROP TABLE IF EXISTS outbox_events;
