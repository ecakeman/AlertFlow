-- Consumer bookkeeping. published_at on outbox_events stays the Kafka ack.

CREATE TABLE processed_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_name TEXT NOT NULL,
    event_id      TEXT NOT NULL,
    event_type    TEXT NOT NULL,
    processed_at  BIGINT NOT NULL,
    UNIQUE (consumer_name, event_id)
);

CREATE TABLE dead_letter_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic        TEXT NOT NULL,
    partition_id INTEGER NOT NULL,
    offset_value BIGINT NOT NULL,
    event_id     TEXT,
    event_type   TEXT,
    payload      JSONB NOT NULL,
    error        TEXT NOT NULL,
    created_at   BIGINT NOT NULL,
    UNIQUE (topic, partition_id, offset_value)
);

CREATE TABLE service_runtime_state (
    service_id     TEXT PRIMARY KEY,
    current_status TEXT NOT NULL CHECK (current_status IN ('online', 'offline', 'warning')),
    last_event_id  TEXT NOT NULL,
    last_check_id  BIGINT NOT NULL,
    last_event_at  BIGINT NOT NULL,
    updated_at     BIGINT NOT NULL
);

CREATE TABLE notification_deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        TEXT NOT NULL,
    incident_id     BIGINT REFERENCES incidents (id) ON DELETE SET NULL,
    integration_id  BIGINT NOT NULL REFERENCES integrations (id),
    event_type      TEXT NOT NULL,
    payload         JSONB NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'running', 'retry_wait', 'succeeded', 'dead')),
    attempt_count   INTEGER NOT NULL DEFAULT 0,
    next_attempt_at BIGINT NOT NULL,
    lease_owner     TEXT,
    lease_until     BIGINT,
    last_error      TEXT,
    created_at      BIGINT NOT NULL,
    updated_at      BIGINT NOT NULL,
    sent_at         BIGINT,
    UNIQUE (event_id, integration_id)
);
CREATE INDEX idx_notification_deliveries_pending ON notification_deliveries (next_attempt_at, id)
    WHERE status = 'pending';

