-- Inbound external alerts are not check rows. external_alert_events dedups
-- the webhook. external_alerts is the current firing/resolved instance.

CREATE TABLE external_alert_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source      TEXT NOT NULL,
    event_id    TEXT NOT NULL,
    alert_key   TEXT NOT NULL,
    service_id  TEXT NOT NULL,
    status      TEXT NOT NULL CHECK (status IN ('firing', 'resolved')),
    occurred_at BIGINT NOT NULL,
    received_at BIGINT NOT NULL,
    title       TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    UNIQUE (source, event_id)
);

CREATE TABLE external_alerts (
    source        TEXT NOT NULL,
    alert_key     TEXT NOT NULL,
    service_id    TEXT NOT NULL,
    status        TEXT NOT NULL CHECK (status IN ('firing', 'resolved')),
    title         TEXT NOT NULL,
    description   TEXT NOT NULL DEFAULT '',
    opened_at     BIGINT NOT NULL,
    resolved_at   BIGINT,
    last_event_id TEXT NOT NULL,
    updated_at    BIGINT NOT NULL,
    PRIMARY KEY (source, alert_key)
);
CREATE INDEX idx_external_alerts_service ON external_alerts (service_id, status);

