-- +goose Up
-- Diagnostic runs reported back by the agent.
--
-- AlertFlow is the store of record for what the UI shows: the agent pushes a
-- result over POST /webhooks/agent and this table keeps it, so reading a report
-- no longer depends on the agent being online. message_id is the agent's stable
-- idempotency key — a redelivery inserts nothing.

CREATE TABLE agent_runs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id     TEXT NOT NULL UNIQUE,
    run_id         TEXT NOT NULL,
    message_type   TEXT NOT NULL DEFAULT '',
    correlation_id TEXT NOT NULL DEFAULT '',
    incident_id    BIGINT,
    service_id     TEXT NOT NULL DEFAULT '',
    event_type     TEXT NOT NULL DEFAULT '',
    mode           TEXT NOT NULL DEFAULT '',
    status         TEXT NOT NULL DEFAULT '',
    report         JSONB,
    evidence       JSONB,
    usage          JSONB,
    error          TEXT NOT NULL DEFAULT '',
    started_at     BIGINT,
    finished_at    BIGINT,
    created_at     BIGINT NOT NULL,
    updated_at     BIGINT NOT NULL
);

-- The incident page asks for the newest result for one incident.
CREATE INDEX idx_agent_runs_incident ON agent_runs (incident_id, updated_at DESC, id DESC);
-- The agent's own run id groups the started/completed/failed messages of one run.
CREATE INDEX idx_agent_runs_run ON agent_runs (run_id, updated_at DESC);

