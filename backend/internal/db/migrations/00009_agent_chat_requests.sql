-- Troubleshooting questions asked of the diagnostic agent.
--
-- Chat used to be a synchronous proxy call, which made the incident page depend
-- on the agent being online and on a model answering inside the HTTP timeout.
-- Now the question is stored here, handed to the agent over the same durable
-- delivery path as a notification, and the answer comes back over
-- POST /webhooks/agent. The page polls this row.
--
-- request_id is the correlation id: it is the delivery's event_id and the
-- agent's idempotency key, so a duplicated send cannot produce a second answer.

CREATE TABLE agent_chat_requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   TEXT NOT NULL UNIQUE,
    incident_id  BIGINT NOT NULL,
    user_id      BIGINT,
    message      TEXT NOT NULL,
    status       TEXT NOT NULL CHECK (status IN ('pending', 'answered', 'failed')),
    delivery_id  BIGINT,
    reply        TEXT,
    evidence_ids JSONB,
    error        TEXT NOT NULL DEFAULT '',
    created_at   BIGINT NOT NULL,
    updated_at   BIGINT NOT NULL
);

CREATE INDEX idx_agent_chat_incident ON agent_chat_requests (incident_id, created_at DESC, id DESC);
CREATE INDEX idx_agent_chat_delivery ON agent_chat_requests (delivery_id);

