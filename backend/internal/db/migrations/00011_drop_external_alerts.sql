-- +goose Up
-- External alert ingestion is gone: AlertFlow no longer accepts alerts pushed
-- in from another system. HTTP checks are the only thing that opens incidents
-- now, so the tables that backed the inbound webhook have no reader left.
--
-- The tables are dropped rather than left orphaned: nothing in the codebase
-- references them, and an empty table that no one writes or reads is worse than
-- no table at all.

DROP TABLE IF EXISTS external_alert_events;
DROP TABLE IF EXISTS external_alerts;

-- +goose Down
-- Not reversible: the data they held came from an ingestion path that no longer
-- exists, so there is nothing to restore it from.
CREATE TABLE IF NOT EXISTS external_alerts (
    source        TEXT NOT NULL,
    alert_key     TEXT NOT NULL,
    service_id    TEXT NOT NULL,
    status        TEXT NOT NULL CHECK (status IN ('firing', 'resolved')),
    title         TEXT NOT NULL,
    description   TEXT NOT NULL DEFAULT '',
    opened_at     BIGINT NOT NULL,
    resolved_at   BIGINT,
    last_event_id TEXT NOT NULL,
    updated_at    BIGINT NOT NULL,
    PRIMARY KEY (source, alert_key)
);
CREATE INDEX IF NOT EXISTS idx_external_alerts_service ON external_alerts (service_id, status);

CREATE TABLE IF NOT EXISTS external_alert_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source      TEXT NOT NULL,
    event_id    TEXT NOT NULL,
    alert_key   TEXT NOT NULL,
    service_id  TEXT NOT NULL,
    status      TEXT NOT NULL CHECK (status IN ('firing', 'resolved')),
    occurred_at BIGINT NOT NULL,
    received_at BIGINT NOT NULL,
    title       TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    UNIQUE (source, event_id)
);
