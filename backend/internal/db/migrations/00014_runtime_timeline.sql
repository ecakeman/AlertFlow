-- Runtime Timeline. Times are Unix seconds, matching incidents and checks.
-- This migration does not copy existing incidents or checks.

CREATE TABLE runtime_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key     TEXT NOT NULL UNIQUE,
    service_id    TEXT NOT NULL,
    source        TEXT NOT NULL,
    event_type    TEXT NOT NULL,
    severity      TEXT NOT NULL,
    title         TEXT NOT NULL,
    summary       TEXT NOT NULL DEFAULT '',
    occurred_at   BIGINT NOT NULL,
    observed_at   BIGINT NOT NULL,
    recorded_at   BIGINT NOT NULL,
    incident_id   BIGINT REFERENCES incidents (id) ON DELETE SET NULL,
    cluster_id    TEXT,
    namespace     TEXT,
    resource_kind TEXT,
    resource_name TEXT,
    resource_uid  TEXT,
    source_ref    JSONB NOT NULL DEFAULT '{}',
    details       JSONB NOT NULL DEFAULT '{}'
);
CREATE INDEX idx_runtime_events_service ON runtime_events (service_id, occurred_at DESC, id DESC);
CREATE INDEX idx_runtime_events_source ON runtime_events (source, occurred_at DESC);
CREATE INDEX idx_runtime_events_incident ON runtime_events (incident_id, occurred_at DESC);

CREATE TABLE runtime_source_state (
    service_id      TEXT NOT NULL,
    source          TEXT NOT NULL,
    enabled         BOOLEAN NOT NULL DEFAULT FALSE,
    status          TEXT NOT NULL,
    last_attempt_at BIGINT,
    last_success_at BIGINT,
    last_error_safe TEXT NOT NULL DEFAULT '',
    cursor          JSONB NOT NULL DEFAULT '{}',
    updated_at      BIGINT NOT NULL,
    PRIMARY KEY (service_id, source)
);

CREATE TABLE runtime_object_states (
    cluster_id       TEXT NOT NULL,
    resource_uid     TEXT NOT NULL,
    service_id       TEXT NOT NULL,
    resource_kind    TEXT NOT NULL,
    namespace        TEXT NOT NULL DEFAULT '',
    resource_name    TEXT NOT NULL DEFAULT '',
    fingerprint      TEXT NOT NULL DEFAULT '',
    snapshot         JSONB NOT NULL DEFAULT '{}',
    resource_version TEXT NOT NULL DEFAULT '',
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    last_seen_at     BIGINT NOT NULL,
    updated_at       BIGINT NOT NULL,
    PRIMARY KEY (cluster_id, resource_uid)
);

